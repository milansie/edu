/** Vrátí novou zamíchanou kopii pole (Fisher–Yates). `rng` vrací číslo z [0, 1). */
export function shuffle(arr, rng = Math.random) {
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
